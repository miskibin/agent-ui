import { MAX_WAIT_SECONDS, TOOL_DEFINITIONS } from "@/lib/subagents/mcp"

export const PI_SUBAGENT_EXTENSION_FILE = "subagents.ts"

/** Self-contained: pi loads this outside the app's module tree through jiti. */
export const PI_SUBAGENT_SOURCE = `// Generated by Agent UI — edits are overwritten. See lib/pi-subagents.ts.
import { Type } from "typebox"

const definitions = ${JSON.stringify(TOOL_DEFINITIONS)}
const maxWait = ${MAX_WAIT_SECONDS}
const instructions = "You can delegate tasks with run_subagent and inspect, wait for, message or cancel them with the other subagent tools. These are real child chats in Agent UI. When the user requests a particular model, use list_models to find its exact id. Use the pi harness for code tasks that need file or shell tools; ollama is chat-only. Give each child a self-contained task."

// Build TypeBox schemas from the bridge's single source of tool definitions.
function schema(value: any): any {
  const options = value.description ? { description: value.description } : {}
  if (value.enum) return Type.Union(value.enum.map((item: any) => Type.Literal(item)), options)
  switch (value.type) {
    case "string": return Type.String(options)
    case "number": return Type.Number(options)
    case "boolean": return Type.Boolean(options)
    case "array": return Type.Array(schema(value.items), options)
    case "object": {
      const required = new Set(value.required ?? [])
      return Type.Object(Object.fromEntries(Object.entries(value.properties ?? {}).map(([key, child]) => {
        const parameter = schema(child)
        return [key, required.has(key) ? parameter : Type.Optional(parameter)]
      })), options)
    }
    default: throw new Error("Unsupported Agent UI tool schema")
  }
}

export default function subagents(pi: any) {
  const url = process.env.AGENT_UI_MCP_URL
  const headers = JSON.parse(process.env.AGENT_UI_MCP_HEADERS || "{}")
  // Child chats receive neither the bridge nor these tools.
  if (!url || !headers.Authorization) return
  let nextId = 0

  async function call(name: string, args: any, signal?: AbortSignal) {
    const timeout = AbortSignal.timeout((maxWait + 20) * 1000)
    const response = await fetch(url, {
      method: "POST",
      redirect: "error",
      headers: { ...headers, "Content-Type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: ++nextId, method: "tools/call", params: { name, arguments: args } }),
      signal: signal ? AbortSignal.any([signal, timeout]) : timeout,
    })
    if (!response.ok) throw new Error("Agent UI subagent bridge answered HTTP " + response.status)
    const message = await response.json()
    if (message.error) throw new Error(message.error.message || "Agent UI bridge request failed")
    const result = message.result
    if (!result || !Array.isArray(result.content)) throw new Error("Invalid Agent UI bridge response")
    if (result.isError) throw new Error(result.content.map((part: any) => part.text ?? "").join("\\n"))
    return { content: result.content, details: result.structuredContent ?? {} }
  }

  pi.on("before_agent_start", (event: any) => ({ systemPrompt: event.systemPrompt + "\\n\\n" + instructions }))
  for (const definition of definitions) {
    pi.registerTool({
      name: definition.name,
      label: definition.name.replaceAll("_", " "),
      description: definition.description,
      promptSnippet: definition.description.split(". ")[0],
      parameters: schema(definition.inputSchema),
      executionMode: "parallel",
      async execute(_id: string, params: any, signal: AbortSignal, onUpdate: any) {
        const launches = definition.name === "run_subagent" || definition.name === "message_subagent"
        const blocking = launches && !params.background
        // Publish the receipt before waiting so the UI can link this tool to
        // the live child even while a blocking delegation is still running.
        let result = await call(definition.name, blocking ? { ...params, background: true } : params, signal)
        const run = result.details
        if (!blocking || !run.run_id) return result
        onUpdate?.(result)
        const seconds = typeof params.wait_seconds === "number" && Number.isFinite(params.wait_seconds)
          ? Math.max(0, Math.min(maxWait, params.wait_seconds)) : maxWait
        const deadline = Date.now() + seconds * 1000
        try {
          while ((result.details.status === "running" || result.details.status === "queued") && Date.now() < deadline) {
            result = await call("get_subagent", {
              run_id: run.run_id, session_id: run.session_id,
              wait_seconds: Math.min(30, Math.ceil((deadline - Date.now()) / 1000)),
              detail: params.detail, since_step: params.since_step, max_answer_chars: params.max_answer_chars,
            }, signal)
            onUpdate?.(result)
          }
          return result
        } catch (error) {
          // Stopping a blocking parent must not leave its delegated work
          // running invisibly. Explicit background runs remain independent.
          if (signal?.aborted) {
            await call("cancel_subagent", { run_id: run.run_id }, AbortSignal.timeout(5000)).catch(() => {})
          }
          throw error
        }
      },
    })
  }
}
`
