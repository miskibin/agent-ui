import assert from "node:assert/strict"
import { test } from "node:test"

import {
  architectureContextLength,
  configuredOllamaNumCtx,
  OLLAMA_DEFAULT_NUM_CTX,
  ollamaOutputBudget,
  servedOllamaContext,
} from "@/lib/ollama-context"

/**
 * Why the composer can read "2.4% of 256k" on a model Ollama will refuse at
 * 4096. `/api/show` reports the architecture's maximum; the runtime default
 * is four thousand, and a Modelfile that never set `num_ctx` is the usual
 * case — ornith-1.5:9b ships 262144 of weights and no PARAMETER at all.
 */

const ORNITH_INFO = { "qwen35.context_length": 262_144 }
const ORNITH_MODELFILE =
  '# Modelfile generated by "ollama show"\nFROM C:\\\\models\\\\blob\nTEMPLATE {{ .Prompt }}\n'

test("architecture length is the weights' ceiling, not the served window", () => {
  assert.equal(architectureContextLength(ORNITH_INFO), 262_144)
  assert.equal(architectureContextLength({ "llama.context_length": 8_192 }), 8_192)
  assert.equal(architectureContextLength({}), undefined)
  assert.equal(architectureContextLength(undefined), undefined)
})

test("a Modelfile with no num_ctx is not a 256k promise", () => {
  assert.equal(configuredOllamaNumCtx({ modelfile: ORNITH_MODELFILE }), undefined)
  assert.equal(servedOllamaContext({ configured: undefined }), OLLAMA_DEFAULT_NUM_CTX)
})

test("parameters may be the aligned text /api/show used to return", () => {
  assert.equal(
    configuredOllamaNumCtx({
      parameters:
        'stop                           "<|im_start|>"\nnum_ctx                        8192\nstop                           "<|im_end|>"\n',
    }),
    8_192
  )
})

test("parameters may be the structured object newer servers return", () => {
  assert.equal(configuredOllamaNumCtx({ parameters: { num_ctx: 16_384 } }), 16_384)
  assert.equal(configuredOllamaNumCtx({ parameters: { numCtx: "4096" } }), 4_096)
  assert.equal(configuredOllamaNumCtx({ parameters: { temperature: 0.7 } }), undefined)
})

test("PARAMETER num_ctx in the Modelfile is the same number", () => {
  assert.equal(
    configuredOllamaNumCtx({
      modelfile: "FROM llama\nPARAMETER num_ctx 32768\nPARAMETER stop <|eot|>\n",
    }),
    32_768
  )
})

test("resolved parameters win over a stale Modelfile line", () => {
  assert.equal(
    configuredOllamaNumCtx({
      parameters: { num_ctx: 8_192 },
      modelfile: "FROM llama\nPARAMETER num_ctx 4096\n",
    }),
    8_192
  )
})

test("a loaded instance is the window the next request will hit", () => {
  assert.equal(
    servedOllamaContext({ running: 4_096, configured: 32_768 }),
    4_096
  )
  assert.equal(servedOllamaContext({ configured: 32_768 }), 32_768)
  assert.equal(servedOllamaContext({}), OLLAMA_DEFAULT_NUM_CTX)
  assert.equal(servedOllamaContext({ running: 0, configured: -1 }), OLLAMA_DEFAULT_NUM_CTX)
})

test("pi's output budget has to fit the window, not its 16k default", () => {
  assert.equal(ollamaOutputBudget(4_096), 1_024)
  assert.equal(ollamaOutputBudget(32_768), 8_192)
  assert.equal(ollamaOutputBudget(128_000), 16_384)
  assert.equal(ollamaOutputBudget(256), 256)
})
